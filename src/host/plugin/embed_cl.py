#!/usr/bin/env python3
"""Embed an OpenCL kernel source file into a C++ header as a raw string.

Usage: python embed_cl.py <input.cl> <output_header.h> [symbol_name]

Used at build time (both the plain cl.exe build script and the optional CMake
target) so the plugin DLL is self-contained — no runtime file paths.
"""
import sys


def main():
    if len(sys.argv) < 3:
        print("usage: embed_cl.py <input.cl> <output_header.h> [symbol_name]", file=sys.stderr)
        return 2
    src_path, out_path = sys.argv[1], sys.argv[2]
    symbol = sys.argv[3] if len(sys.argv) > 3 else "KFM_EDGELEVEL_CL"
    with open(src_path, "r", encoding="utf-8") as f:
        src = f.read()
    # The raw-string delimiter must not appear in the source.
    delim = "CLSRC_END"
    if delim in src:
        print("source contains the raw string delimiter %r" % delim, file=sys.stderr)
        return 1
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by src/host/plugin/embed_cl.py from %s — do not edit.\n"
                % src_path.replace("\\", "/"))
        f.write('static const char %s[] = R"%s(\n%s)%s";\n' % (symbol, delim, src, delim))
    return 0


if __name__ == "__main__":
    sys.exit(main())
